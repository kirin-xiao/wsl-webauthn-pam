#[cfg(test)]
mod tests {
    use sha2::{Digest as _, Sha256};

    /// The bundled root MUST hash to the compile-time pinned fingerprint; otherwise a
    /// chain completed with it could be accepted under a wrong pin. This guards the
    /// vendored bytes against tampering or a bad copy.
    #[test]
    fn bundled_root_matches_pinned_fingerprint() {
        let digest = Sha256::digest(super::MS_TPM_ROOT_2014_DER);
        let mut got = [0u8; 32];
        got.copy_from_slice(&digest);
        assert_eq!(got, crate::MS_TPM_ROOT_2014_SHA256);
    }
}
